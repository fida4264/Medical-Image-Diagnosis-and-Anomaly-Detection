"""
histopathology/reports/performance_report.py
=============================================
Performance report generator for histopathology evaluation.
Produces both Markdown and JSON reports. Mirrors Module 7/8/9 pattern.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any, Dict, Tuple

logger = logging.getLogger(__name__)


class PerformanceReportGenerator:
    """Generates Markdown and JSON performance reports from evaluation results."""

    @staticmethod
    def save(
        results: Dict[str, Any],
        label_map: Dict[str, int],
        output_dir: Path,
    ) -> Tuple[Path, Path]:
        """Save JSON and Markdown performance reports to output_dir."""
        output_dir = Path(output_dir)
        output_dir.mkdir(parents=True, exist_ok=True)

        json_path = output_dir / "performance_report.json"
        md_path = output_dir / "performance_report.md"

        gm = results["global_metrics"]
        per_class = results.get("per_class_metrics", {})
        num_samples = results.get("num_samples", 0)
        inf_time = results.get("inference_time_s", 0.0)

        # JSON report
        report_dict = {
            "module": "histopathology",
            "modality": "histopathology",
            "num_test_samples": num_samples,
            "inference_time_s": round(inf_time, 4),
            "global_metrics": {
                "accuracy": round(gm.get("accuracy", 0.0), 6),
                "f1_macro": round(gm.get("f1_macro", 0.0), 6),
                "f1_weighted": round(gm.get("f1_weighted", 0.0), 6),
                "precision_macro": round(gm.get("precision_macro", 0.0), 6),
                "recall_macro": round(gm.get("recall_macro", 0.0), 6),
            },
            "per_class_metrics": per_class,
            "label_map": label_map,
        }
        with open(json_path, "w", encoding="utf-8") as f:
            json.dump(report_dict, f, indent=2)

        # Markdown report
        acc = gm.get("accuracy", 0.0)
        f1_macro = gm.get("f1_macro", 0.0)
        f1_weighted = gm.get("f1_weighted", 0.0)

        md_lines = [
            "# Histopathology Cancer Subtyping — Performance Report",
            "",
            "## Module 10 | Histopathology Cancer Subtyping Framework",
            "",
            "| Metric | Value |",
            "|--------|-------|",
            f"| Test Samples | {num_samples} |",
            f"| Accuracy | {acc*100:.2f}% |",
            f"| F1 Macro | {f1_macro:.4f} |",
            f"| F1 Weighted | {f1_weighted:.4f} |",
            f"| Precision Macro | {gm.get('precision_macro', 0.0):.4f} |",
            f"| Recall Macro | {gm.get('recall_macro', 0.0):.4f} |",
            f"| Total Inference Time | {inf_time:.2f}s |",
            "",
            "## Per-Class Metrics",
            "",
            "| Class | Precision | Recall | F1 |",
            "|-------|-----------|--------|----|",
        ]
        for cls_name, cls_metrics in per_class.items():
            md_lines.append(
                f"| {cls_name} | {cls_metrics['precision']:.4f} | {cls_metrics['recall']:.4f} | {cls_metrics['f1']:.4f} |"
            )

        md_lines += [
            "",
            "## Cancer Subtypes Discovered",
            "",
        ]
        for cls_name, cls_idx in label_map.items():
            md_lines.append(f"- `{cls_idx}`: {cls_name}")

        md_lines += ["", "---", "*Generated by Module 10: Histopathology Cancer Subtyping Framework*"]

        with open(md_path, "w", encoding="utf-8") as f:
            f.write("\n".join(md_lines))

        logger.info(f"Performance reports saved: '{json_path}', '{md_path}'.")
        return json_path, md_path
