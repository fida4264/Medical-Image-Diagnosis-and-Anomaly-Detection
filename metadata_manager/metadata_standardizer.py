"""
metadata_manager/metadata_standardizer.py
==========================================
Core standardization engine for Module 2.

Takes the raw DataFrame from MetadataLoader and produces the unified
master_metadata.csv — the single source of truth for all downstream modules.

What this module does
---------------------
1. Normalises modality names  (Ultrasound → ultrasound)
2. Extracts true disease class from the image path for datasets where
   Module 1's disease_class field is the dataset folder name, not the disease.
3. Derives dataset_name and dataset_source for each row.
4. Assigns channel count (1 = grayscale, 3 = RGB) based on modality.
5. Applies ClassMapper to produce the normalized_class column.
6. Adds internal_id (generated by ImageMapper).
7. Selects and orders the 15 columns required by the master_metadata spec.
8. Saves master_metadata.csv.

Classes
-------
MetadataStandardizer
    Orchestrates the full standardization pipeline.

Author: Medical AI System — Module 2
"""

import logging
from pathlib import Path
from typing import Optional

import pandas as pd

from metadata_manager.class_mapper import ClassMapper
from metadata_manager.config import (
    COL_IMAGE_ID,
    COL_INTERNAL_ID,
    COL_DATASET_NAME,
    COL_DATASET_SOURCE,
    COL_MODALITY,
    COL_DISEASE,
    COL_NORMALIZED_CLASS,
    COL_ORIGINAL_CLASS,
    COL_SPLIT,
    COL_IMAGE_PATH,
    COL_EXTENSION,
    COL_WIDTH,
    COL_HEIGHT,
    COL_CHANNELS,
    COL_FILE_SIZE,
    MASTER_METADATA_COLUMNS,
    MODALITY_NORMALIZE,
    MODALITY_CHANNELS,
    EXTRACTION_STRATEGIES,
    DATASET_REGISTRY_INFO,
    METADATA_OUTPUT_DIR,
    MASTER_METADATA_CSV,
)

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# Path-based disease class extraction helpers
# ---------------------------------------------------------------------------

def _extract_disease_from_path(
    image_path: str,
    modality_norm: str,
    disease_class_raw: str,
) -> str:
    """
    Extract the true disease class from the image file path.

    Uses the EXTRACTION_STRATEGIES table from config.py.  The strategy
    describes where in the path the disease class lives:

    * USE_EXISTING   — disease_class_raw is already correct
    * PARENT_FOLDER  — parent folder of the image file
    * ANCHOR_OFFSET  — N levels after a named anchor folder
    * UNKNOWN        — cannot extract; return 'unknown'

    Parameters
    ----------
    image_path : str
        Absolute path to the image file.
    modality_norm : str
        Normalised modality name (e.g. 'chest_xray').
    disease_class_raw : str
        The disease_class value from Module 1's metadata.csv.

    Returns
    -------
    str
        Extracted disease class string (un-normalised).
    """
    key = (modality_norm, disease_class_raw)
    strategy_info = EXTRACTION_STRATEGIES.get(key)

    if strategy_info is None:
        # Default: try parent folder then fall back to disease_class_raw
        parent = Path(image_path).parent.name
        return parent if parent else disease_class_raw

    strategy = strategy_info["strategy"]

    if strategy == "USE_EXISTING":
        return disease_class_raw

    if strategy == "PARENT_FOLDER":
        return Path(image_path).parent.name

    if strategy == "ANCHOR_OFFSET":
        anchor: str = strategy_info["anchor"]
        offset: int = strategy_info.get("offset", 1)
        parts = Path(image_path).parts
        try:
            idx = next(i for i, p in enumerate(parts) if p == anchor)
            target_idx = idx + offset
            if target_idx < len(parts):
                return parts[target_idx]
        except StopIteration:
            pass
        return disease_class_raw

    # UNKNOWN or unrecognised strategy
    return "unknown"


def _get_dataset_info(disease_class_raw: str) -> tuple:
    """Return (dataset_name, dataset_source) for a raw disease_class value."""
    info = DATASET_REGISTRY_INFO.get(disease_class_raw, {})
    name = info.get("name", disease_class_raw)
    source = info.get("source", "Unknown")
    return name, source


# ---------------------------------------------------------------------------
# Main class
# ---------------------------------------------------------------------------

class MetadataStandardizer:
    """
    Transforms raw Module 1 metadata into the unified master_metadata schema.

    Parameters
    ----------
    metadata_df : pd.DataFrame
        Raw metadata DataFrame from MetadataLoader.
    class_mapper : ClassMapper
        Initialised ClassMapper instance.
    outputs_dir : Path, optional
        Where to save master_metadata.csv.

    Usage
    -----
        standardizer = MetadataStandardizer(metadata_df, class_mapper)
        master_df = standardizer.standardize()
        standardizer.save()
    """

    def __init__(
        self,
        metadata_df: pd.DataFrame,
        class_mapper: ClassMapper,
        outputs_dir: Optional[Path] = None,
    ) -> None:
        self._raw_df: pd.DataFrame = metadata_df.copy()
        self._class_mapper = class_mapper
        self._outputs_dir: Path = Path(outputs_dir) if outputs_dir else METADATA_OUTPUT_DIR
        self._master_df: Optional[pd.DataFrame] = None

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def standardize(self) -> pd.DataFrame:
        """
        Run the full standardization pipeline.

        Returns
        -------
        pd.DataFrame
            master_metadata DataFrame (all rows, MASTER_METADATA_COLUMNS).
        """
        logger.info("Starting metadata standardization on %d records ...", len(self._raw_df))

        df = self._raw_df.copy()

        # Step 1 — Normalise modality names
        df[COL_MODALITY] = df["modality"].map(
            lambda m: MODALITY_NORMALIZE.get(m, m.lower())
        )
        logger.info("  [1/7] Modality names normalised.")

        # Step 2 — Extract true disease class from image path
        logger.info("  [2/7] Extracting disease classes from image paths ...")
        df[COL_DISEASE] = df.apply(
            lambda row: _extract_disease_from_path(
                row["image_path"],
                row[COL_MODALITY],
                row["disease_class"],
            ),
            axis=1,
        )
        logger.info("  [2/7] Disease class extraction complete.")

        # Step 3 — Preserve original class (before normalization)
        df[COL_ORIGINAL_CLASS] = df[COL_DISEASE]

        # Step 4 — Normalise class names
        df[COL_NORMALIZED_CLASS] = self._class_mapper.apply(df[COL_DISEASE])
        logger.info("  [3/7] Class names normalised.")

        # Step 5 — Dataset name and source
        info_tuples = df["disease_class"].map(_get_dataset_info)
        df[COL_DATASET_NAME] = info_tuples.map(lambda t: t[0])
        df[COL_DATASET_SOURCE] = info_tuples.map(lambda t: t[1])
        logger.info("  [4/7] Dataset names and sources assigned.")

        # Step 6 — Channels based on modality
        df[COL_CHANNELS] = df[COL_MODALITY].map(
            lambda m: MODALITY_CHANNELS.get(m, 3)
        )
        logger.info("  [5/7] Channel counts assigned.")

        # Step 7 — Rename / alias columns to master schema
        df = df.rename(columns={
            "image_id": COL_IMAGE_ID,
            "image_path": COL_IMAGE_PATH,
            "extension": COL_EXTENSION,
            "width": COL_WIDTH,
            "height": COL_HEIGHT,
            "file_size_bytes": COL_FILE_SIZE,
            "split": COL_SPLIT,
        })
        # internal_id will be assigned by ImageMapper — placeholder for now
        df[COL_INTERNAL_ID] = ""
        logger.info("  [6/7] Column schema aligned.")

        # Step 8 — Select and order final columns
        available = [c for c in MASTER_METADATA_COLUMNS if c in df.columns]
        self._master_df = df[available].reset_index(drop=True)
        logger.info(
            "  [7/7] Standardization complete. Shape: %s",
            self._master_df.shape,
        )
        return self._master_df

    def assign_internal_ids(self, id_series: pd.Series) -> None:
        """
        Inject internal IDs produced by ImageMapper into master_df.

        Parameters
        ----------
        id_series : pd.Series
            Series of internal ID strings, same length and index as master_df.
        """
        if self._master_df is None:
            raise RuntimeError("standardize() must be called first.")
        self._master_df[COL_INTERNAL_ID] = id_series

    def save(self, output_dir: Optional[Path] = None) -> Path:
        """
        Save master_metadata.csv to disk.

        Returns
        -------
        Path
            The path of the saved CSV file.

        Raises
        ------
        RuntimeError
            If standardize() has not been called first.
        """
        if self._master_df is None:
            raise RuntimeError("standardize() must be called before save().")
        dest_dir = Path(output_dir) if output_dir else self._outputs_dir
        dest_dir.mkdir(parents=True, exist_ok=True)
        dest = dest_dir / MASTER_METADATA_CSV
        self._master_df.to_csv(dest, index=False, encoding="utf-8")
        logger.info(
            "master_metadata.csv saved -> %s  (%d rows)", dest, len(self._master_df)
        )
        return dest

    @property
    def master_df(self) -> Optional[pd.DataFrame]:
        """The standardised master_metadata DataFrame, or None before standardize()."""
        return self._master_df
